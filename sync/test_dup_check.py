"""เทส dup_check — ตัวตรวจนักเรียนที่มีชื่ออยู่เกิน 1 โครงงาน

ชื่อคนในเทสเป็นชื่อสมมติ ยกเว้นสองเคสท้ายไฟล์ที่เป็นข้อมูลจริงจากไฟล์ที่ครูส่งมา (ผู้ใช้ยืนยัน
แล้วว่าเป็นข้อมูลผิดที่ต้องให้ครูไปแก้ ไม่ใช่สำเนาซ้ำ) เก็บไว้เป็นตัวล็อกว่าสองเคสนี้ต้องขึ้นเตือน
"""
import pytest

from sync.dup_check import (
    find_cross_room_duplicates,
    find_room_duplicates,
    has_surname,
    name_key,
)


def proj(room, ord_, name, members, advisor="นางสาวมาลี รักเรียน"):
    return {"room": room, "ord": ord_, "name": name, "members": members, "advisor": advisor}


# --- name_key ----------------------------------------------------------------
@pytest.mark.parametrize("name, expected", [
    ("เด็กหญิงพรธิวา คำสอน", "พรธิวาคำสอน"),
    ("ด.ญ.ชลิตา คายุ", "ชลิตาคายุ"),
    ("น.ส. ชลิตา  คายุ", "ชลิตาคายุ"),
    ("น.ส ชลิตา คายุ", "ชลิตาคายุ"),      # ครูพิมพ์ "น.ส" ไม่มีจุดท้าย (เจอใน ม.4/1)
    ("นางสาวมาลี รักเรียน", "มาลีรักเรียน"),
    ("", ""),
    (None, ""),
])
def test_name_key(name, expected):
    assert name_key(name) == expected


def test_name_key_สระอำที่หลุดจาก_pdf_ต้องแมตช์กับไฟล์_docx():
    """ข้อความจาก PDF ทำ "คำสอน" เป็น "ค าสอน" ถ้าไม่ซ่อมก่อนลบช่องว่างจะไม่แมตช์กัน"""
    assert name_key("เด็กหญิงพรธิวา ค าสอน") == name_key("เด็กหญิงพรธิวา คำสอน")
    assert name_key("เด็กหญิงเชื้อวังค า") == "เชื้อวังคำ"


def test_name_key_คำนำหน้ายาวต้องชนะคำนำหน้าสั้น():
    assert name_key("นางสาวมาลี ใจดี") == "มาลีใจดี"      # ไม่ใช่ "สาวมาลีใจดี"
    assert name_key("เด็กหญิงมาลี ใจดี") == "มาลีใจดี"


@pytest.mark.parametrize("name, expected", [
    ("เด็กหญิงพรธิวา คำสอน", True),
    ("เด็กหญิงกฤติภรณ์", False),
    ("นางสาวมาลี", False),
    ("", False),
])
def test_has_surname(name, expected):
    assert has_surname(name) is expected


# --- find_room_duplicates ----------------------------------------------------
def test_ไม่มีชื่อซ้ำได้ลิสต์ว่าง():
    assert find_room_duplicates([proj("ม.1/1", 1, "ก", ["เด็กชายสมชาย ใจดี"])]) == []
    assert find_room_duplicates([]) == []


def test_ชื่อเต็มซ้ำข้ามโครงงานในห้องเดียวกันคือ_confirmed():
    out = find_room_duplicates([
        proj("ม.2/5", 6, "พิชิตห้องเรียนสะอาด", ["ด.ญ.ชลิตา คายุ", "ด.ช.สมชาย ใจดี"]),
        proj("ม.2/5", 7, "เครื่องดื่มสมุนไพร", ["ด.ญ.ชลิตา คายุ"]),
    ])
    assert out == [{"room": "ม.2/5", "student": "ด.ญ.ชลิตา คายุ", "level": "confirmed",
                    "count": 2, "ords": [6, 7],
                    "projects": ["พิชิตห้องเรียนสะอาด", "เครื่องดื่มสมุนไพร"]}]


def test_ชื่อซ้ำสองครั้งในโครงงานเดียวก็ต้องเตือน():
    """เจอจริงที่ ม.3/5 #2 — ครูพิมพ์ชื่อเด็กคนเดิมสองรอบในกลุ่มเดียว ทำให้ยอดนักเรียนเกิน"""
    out = find_room_duplicates([
        proj("ม.3/5", 2, "การพัฒนาทักษะภาษาจีน",
             ["เด็กหญิงพรธิวา คำสอน", "เด็กหญิงพรธิวา คำสอน", "เด็กหญิงอัยรดา วุฒิคุณ"]),
    ])
    assert [(w["student"], w["count"], w["ords"]) for w in out] == [
        ("เด็กหญิงพรธิวา คำสอน", 2, [2])]


def test_ชื่อเดี่ยวไม่มีนามสกุลที่ซ้ำคือ_likely():
    out = find_room_duplicates([
        proj("ม.1/1", 1, "ก", ["เด็กหญิงกฤติภรณ์"]),
        proj("ม.1/1", 2, "ข", ["เด็กหญิงกฤติภรณ์"]),
    ])
    assert [(w["student"], w["level"]) for w in out] == [("เด็กหญิงกฤติภรณ์", "likely")]


def test_ชื่อครูที่ปรึกษาที่หลุดเข้า_members_ไม่ถูกเตือน():
    """ครูคนเดียวคุมหลายโครงงานในห้อง ถ้าไม่กรองออกจะขึ้นเตือนทุกห้องที่ชื่อครูหลุดเข้าไป"""
    out = find_room_duplicates([
        proj("ม.5/4", 1, "ก", ["นางสาวพิมพ์ใจ ตั้งมั่น", "นางสาวมาลี รักเรียน"]),
        proj("ม.5/4", 2, "ข", ["นางสาวอรุณี ขยัน", "นางสาวมาลี รักเรียน"]),
    ])
    assert out == []


def test_ชื่อครูคนอื่นในระบบก็ถูกกรองออก():
    """ม.4-ม.5 นักเรียนใช้คำนำหน้า นาย/นางสาว เหมือนครู แยกด้วยคำนำหน้าไม่ได้"""
    projects = [
        proj("ม.4/1", 1, "ก", ["นางสาวกัญชพร วิเชียร"], advisor="นางสาววาสนา แสงสว่าง"),
        proj("ม.4/1", 2, "ข", ["นางสาวกัญชพร วิเชียร"], advisor="นางสาววาสนา แสงสว่าง"),
    ]
    assert find_room_duplicates(projects) != []                     # ไม่รู้ว่าเป็นครูก็ต้องเตือน
    assert find_room_duplicates(projects, ["ครูกัญชพร วิเชียร"]) == []


def test_คนละห้องไม่นับว่าซ้ำกัน():
    assert find_room_duplicates([
        proj("ม.1/1", 1, "ก", ["เด็กชายสมชาย ใจดี"]),
        proj("ม.1/2", 1, "ข", ["เด็กชายสมชาย ใจดี"]),
    ]) == []


def test_ชื่อที่สะกดต่างกันเพราะ_pdf_ถือเป็นคนเดียวกัน():
    out = find_room_duplicates([
        proj("ม.3/5", 1, "ก", ["เด็กหญิงพรธิวา คำสอน"]),
        proj("ม.3/5", 2, "ข", ["เด็กหญิงพรธิวา ค าสอน"]),
    ])
    assert len(out) == 1 and out[0]["count"] == 2


def test_เรียงตามห้องแล้วลำดับโครงงาน():
    out = find_room_duplicates([
        proj("ม.1/2", 3, "ค", ["เด็กชายสมชาย ใจดี"]),
        proj("ม.1/2", 1, "ก", ["เด็กชายสมชาย ใจดี"]),
        proj("ม.1/1", 5, "ง", ["เด็กหญิงมาลี ใจงาม"]),
        proj("ม.1/1", 2, "จ", ["เด็กหญิงมาลี ใจงาม"]),
    ])
    assert [(w["room"], w["ords"]) for w in out] == [("ม.1/1", [2, 5]), ("ม.1/2", [1, 3])]


def test_ชื่อว่างหรือขีดไม่ถูกนับว่าซ้ำ():
    assert find_room_duplicates([proj("ม.1/1", 1, "ก", ["", "", "-"])]) == []


# --- find_cross_room_duplicates ----------------------------------------------
def test_ชื่อเต็มที่โผล่หลายห้องถูกเตือนข้ามห้อง():
    out = find_cross_room_duplicates([
        proj("ม.1/1", 1, "ก", ["เด็กชายสมชาย ใจดี"]),
        proj("ม.2/3", 4, "ข", ["เด็กชายสมชาย ใจดี"]),
    ])
    assert out == [{"student": "เด็กชายสมชาย ใจดี", "rooms": ["ม.1/1", "ม.2/3"]}]


def test_ชื่อเดี่ยวไม่เตือนข้ามห้อง():
    """เด็กชื่อต้นเดียวกันคนละห้องเป็นเรื่องปกติ — 206 จาก 1,486 ชื่อไม่มีนามสกุล"""
    assert find_cross_room_duplicates([
        proj("ม.1/1", 1, "ก", ["เด็กหญิงกฤติภรณ์"]),
        proj("ม.2/3", 4, "ข", ["เด็กหญิงกฤติภรณ์"]),
    ]) == []


def test_ชื่อซ้ำในห้องเดียวไม่ใช่เคสข้ามห้อง():
    assert find_cross_room_duplicates([
        proj("ม.1/1", 1, "ก", ["เด็กชายสมชาย ใจดี"]),
        proj("ม.1/1", 2, "ข", ["เด็กชายสมชาย ใจดี"]),
    ]) == []


def test_has_surname_ขีดแทนนามสกุลไม่นับเป็นชื่อเต็ม():
    """เจอจริงที่ ม.1/3 — ถ้านับเป็นชื่อเต็มจะไปเตือนข้ามห้องกับเด็กชื่อเดียวกันห้องอื่น"""
    assert has_surname("เด็กชายอาทิตย์ –") is False
    assert find_cross_room_duplicates([
        proj("ม.1/3", 1, "ก", ["เด็กชายอาทิตย์ –"]),
        proj("ม.1/11", 2, "ข", ["เด็กชายอาทิตย์"]),
    ]) == []
